def _set_text(par: Paragraph, text, bold, italic):
    """Текст в первый run (остальные чистим) — как делает движок render_docx."""
    if not par.runs:
        par.add_run("")
    par.runs[0].text = text
    par.runs[0].bold = bold
    par.runs[0].italic = italic
    par.runs[0].underline = False
    for r in par.runs[1:]:
        r.text = ""
    return par


def _replace_with(par: Paragraph, rows):
    """Заменить абзац-донор на несколько абзацев с его же оформлением."""
    anchor = par._p
    made = []
    for text, bold, italic in rows:
        new_p = copy.deepcopy(par._p)
        anchor.addnext(new_p)
        anchor = new_p
        made.append(_set_text(Paragraph(new_p, par._parent), text, bold, italic))
    par._p.getparent().remove(par._p)  # донор убираем
    return made


def _find(doc, needle):
    for p in doc.paragraphs:
        if needle.lower() in (p.text or "").lower():
            return p
    return None


class Command(BaseCommand):
    help = "Собрать недостающие .docx-шаблоны запросов и уведомлений из базовых"

    def add_arguments(self, parser):
        parser.add_argument("--force", action="store_true", help="перезаписать существующие")

    def handle(self, *args, **opts):
        force = opts["force"]
        made = skipped = 0

        for fname, body in REQUESTS.items():
            out = TPL_DIR / fname
            if out.exists() and not force:
                self.stdout.write(f"  = {fname} (уже есть, --force для перезаписи)")
                skipped += 1
                continue
            doc = Document(str(TPL_DIR / BASE_REQUEST))
            marker = _find(doc, "ТЕКСТ ЗАПРОСА")
            if marker is None:
                self.stderr.write(self.style.ERROR(
                    f"{BASE_REQUEST}: не найден абзац «ТЕКСТ ЗАПРОСА»"))
                return
            _replace_with(marker, body)
            doc.save(str(out))
            self.stdout.write(self.style.SUCCESS(f"  + {fname} ({len(body)} абз. тела)"))
            made += 1

        for fname, spec in NOTICES.items():
            out = TPL_DIR / fname
            if out.exists() and not force:
                self.stdout.write(f"  = {fname} (уже есть, --force для перезаписи)")
                skipped += 1
                continue
            doc = Document(str(TPL_DIR / BASE_LETTER))
            title = _find(doc, "ИНФОРМАЦИОННОЕ ПИСЬМО")
            if title is None:
                self.stderr.write(self.style.ERROR(
                    f"{BASE_LETTER}: не найден заголовок «ИНФОРМАЦИОННОЕ ПИСЬМО»"))
                return
            _set_text(title, spec["title"], True, True)
            # Тело инф. письма: от «В соответствии со ст. 213.25…» до «Приложение:».
            start = _find(doc, "В соответствии со ст. 213.25")
            if start is None:
                self.stderr.write(self.style.ERROR(f"{BASE_LETTER}: не найдено начало тела"))
                return
            # 🛑 doc.paragraphs каждый раз отдаёт НОВЫЕ объекты Paragraph — искать
            # индекс через list.index() нельзя, сравниваем по XML-элементу (._p).
            paras = doc.paragraphs
            i0 = next(i for i, p in enumerate(paras) if p._p is start._p)
            i1 = next((i for i in range(i0, len(paras))
                       if paras[i].text.strip().startswith("Приложение")), len(paras))
            for p in paras[i0 + 1:i1]:      # хвост старого тела убираем
                p._p.getparent().remove(p._p)
            _replace_with(start, spec["body"])  # первый абзац тела → новое тело
            doc.save(str(out))
            self.stdout.write(self.style.SUCCESS(
                f"  + {fname} ({len(spec['body'])} абз. тела)"))
            made += 1

        self.stdout.write(self.style.SUCCESS(f"Готово: собрано {made}, пропущено {skipped}"))
        self.stdout.write(self.style.WARNING(
            "🛑 Тексты — юридические формулировки, вычитайте. Далее: "
            "python manage.py load_request_templates --force"))
