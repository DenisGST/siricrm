"""Разбор номера арбитражного дела (А12-8439/2026) для поиска.

🛑 Главная ловушка: в номерах дел «А» — **кириллическая** (U+0410), а пользователь
в латинской раскладке наберёт «A» (U+0041). Символы визуально неразличимы, но для
БД это разные буквы, и запрос латиницей не найдёт кириллический номер. В самой базе
тоже разнобой: подавляющее большинство — кириллица, но попадаются латиница, строчная
«а» и префикс «№». Поэтому ищем сразу по ОБОИМ вариантам буквы; регистр («а» vs «А»)
берёт на себя ILIKE (`icontains`), а префикс «№» и пробелы — то же `icontains`.
"""
import re

# «А12-8439/2026», а также «A12-8439/2026», «№ А12 - 8439 / 26», «12-8439/2026».
# Буква необязательна: по одним цифрам номер тоже узнаётся однозначно.
# Год тоже необязателен — по частичному вводу «А12-4684» дело должно находиться
# (в т.ч. пока номер ещё дописывают).
_CASE_RE = re.compile(
    r"^\s*№?\s*[АA]?\s*(\d{1,3})\s*[-–—]\s*(\d{1,7})\s*(?:/\s*(\d{2,4}))?\s*$",
    re.IGNORECASE,
)

_CYR_A = "А"  # U+0410
_LAT_A = "A"  # U+0041


def case_number_variants(q: str) -> list[str]:
    """Запрос → варианты номера дела для `icontains`.

    Пустой список, если строка не похожа на номер дела. Числа НЕ нормализуем
    через int() — это срезало бы ведущий ноль в коде региона (А07-…).

    Без года («А12-4684») отдаём префикс — `icontains` подберёт дело с любым
    годом. Совпадение при этом частичное (запрос «А12-468» найдёт и «А12-4684/…»),
    и для живой подсказки это как раз нужно.
    """
    m = _CASE_RE.match(q or "")
    if not m:
        return []
    region, num, year = m.groups()

    if not year:
        core = f"{region}-{num}"
        return [f"{_CYR_A}{core}", f"{_LAT_A}{core}"]

    years = [year]
    if len(year) == 2:
        # «/26» → в базе лежит «/2026»; ищем и так, и так.
        years.append(f"20{year}")

    out = []
    for y in years:
        core = f"{region}-{num}/{y}"
        out.append(f"{_CYR_A}{core}")
        out.append(f"{_LAT_A}{core}")
    return out
